/**
 * 边框圆角类型枚举
 */
export var BorderRadiusType;
(function (BorderRadiusType) {
    BorderRadiusType[BorderRadiusType["None"] = 0] = "None";
    BorderRadiusType[BorderRadiusType["Small"] = 0.25] = "Small";
    BorderRadiusType[BorderRadiusType["Medium"] = 0.5] = "Medium";
    BorderRadiusType[BorderRadiusType["Large"] = 0.75] = "Large";
    BorderRadiusType[BorderRadiusType["Full"] = 1] = "Full";
})(BorderRadiusType || (BorderRadiusType = {}));
